"""Generate a SYNTHETIC sensor-telemetry demonstration dataset.

IMPORTANT -- this is fabricated demonstration data, not real mining data.
It exists to exercise the parts of the original project design that the
real Data Repo (a Limble CMMS export, see docs/dataset_mapping.md) cannot
support: continuous sensor telemetry, lag/rolling/trend features,
near-term failure-horizon labels, chronological validation, and an
LSTM/GRU sequence model. It is saved under data/raw/synthetic/ -- never
merged with or presented as the real Data Repo -- and every downstream
report/page that uses it must say so explicitly.

Simulation design: each synthetic machine runs "healthy" (sensor readings
centered on a nominal baseline with noise) until a randomly-timed
degradation episode begins -- vibration and pressure ramp upward over a
random 48-168 hour window, culminating in a labeled failure event, after
which the machine resets to a fresh healthy baseline (simulating a repair).
This creates genuine, learnable pre-failure drift for the ML pipeline to
find, rather than pure noise.

Usage:
    python scripts/generate_synthetic_dataset.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import numpy as np
import pandas as pd

from config.settings import PATHS, RANDOM_SEED

N_MACHINES = 25
DAYS = 120
HOURS_PER_DAY = 24
CATEGORIES = ["Pump", "Motor", "Compressor", "Conveyor"]
MANUFACTURERS = ["SynCorp", "DemoWorks", "FabriDrive"]

BASELINES = {
    "voltage": (400.0, 5.0),      # (mean, std) -- volts
    "rotation": (1480.0, 15.0),   # RPM
    "pressure": (6.0, 0.3),       # bar
    "vibration": (2.5, 0.4),      # mm/s
}


def _simulate_machine(machine_id: str, rng: np.random.Generator) -> pd.DataFrame:
    n_hours = DAYS * HOURS_PER_DAY
    timestamps = pd.date_range("2025-01-01", periods=n_hours, freq="h")

    voltage = rng.normal(*BASELINES["voltage"], size=n_hours)
    rotation = rng.normal(*BASELINES["rotation"], size=n_hours)
    pressure = rng.normal(*BASELINES["pressure"], size=n_hours)
    vibration = rng.normal(*BASELINES["vibration"], size=n_hours)
    failure_event = np.zeros(n_hours, dtype=int)

    # Schedule 2-4 degradation episodes across the simulated period.
    n_episodes = rng.integers(2, 5)
    episode_starts = sorted(rng.integers(200, n_hours - 200, size=n_episodes))
    for start in episode_starts:
        ramp_len = int(rng.integers(48, 168))
        end = min(start + ramp_len, n_hours - 1)
        ramp = np.linspace(0, 1, end - start)
        # Vibration and pressure drift upward as the fault develops.
        vibration[start:end] += ramp * rng.uniform(4.0, 8.0)
        pressure[start:end] += ramp * rng.uniform(1.0, 2.5)
        rotation[start:end] -= ramp * rng.uniform(50, 120)
        failure_event[end] = 1

    return pd.DataFrame(
        {
            "machine_id": machine_id,
            "timestamp": timestamps,
            "voltage": voltage,
            "rotation": rotation,
            "pressure": pressure,
            "vibration": vibration,
            "failure_event": failure_event,
        }
    )


def generate(seed: int = RANDOM_SEED) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    frames = []
    for i in range(N_MACHINES):
        machine_id = f"SYN-{CATEGORIES[i % len(CATEGORIES)].upper()[:2]}-{i:03d}"
        frame = _simulate_machine(machine_id, rng)
        frame["equipment_category"] = CATEGORIES[i % len(CATEGORIES)]
        frame["manufacturer"] = MANUFACTURERS[i % len(MANUFACTURERS)]
        frames.append(frame)
    return pd.concat(frames, ignore_index=True)


def main() -> None:
    out_dir = PATHS["raw_excel"].parent / "synthetic"
    out_dir.mkdir(parents=True, exist_ok=True)

    df = generate()
    out_path = out_dir / "synthetic_sensor_telemetry.csv"
    df.to_csv(out_path, index=False)

    readme_path = out_dir / "README.md"
    readme_path.write_text(
        "# SYNTHETIC DEMONSTRATION DATA -- NOT REAL MINE DATA\n\n"
        "Generated by scripts/generate_synthetic_dataset.py (fixed random "
        f"seed={RANDOM_SEED} for reproducibility). Simulates hourly sensor "
        "telemetry (voltage, rotation, pressure, vibration) with labeled "
        "failure events, to demonstrate the time-series-dependent parts of "
        "the project design (lag/rolling/trend features, chronological "
        "split, near-term failure-horizon labels, LSTM/GRU) that the real "
        "Data Repo (a CMMS snapshot, not sensor telemetry) cannot support. "
        "See docs/synthetic_demo_track.md.\n",
        encoding="utf-8",
    )

    print(f"Generated {len(df)} rows across {N_MACHINES} synthetic machines.")
    print(f"Failure events: {df['failure_event'].sum()}")
    print(f"Saved to: {out_path}")
    print(f"Disclaimer written to: {readme_path}")


if __name__ == "__main__":
    main()
